"""Assemble editable sources; validate local Markdown links. No network or research data."""
from pathlib import Path
import json,re,hashlib
ROOT=Path(__file__).resolve().parents[1]
parts=sorted((ROOT/'chapters').glob('*.md'))+[ROOT/'REFERENCES.md']+sorted((ROOT/'appendices').glob('*.md'))
text='<!-- Generated by tools/build_draft.py; edit chapter/appendix source files. -->\n\n'
text+='## Draft contents\n\n'+'\n'.join(f'- [{p.stem}]({p.relative_to(ROOT)})' for p in parts)+'\n\n---\n\n'
for p in parts:
 content=p.read_text()
 # Chapter/appendix sources sit one directory below the assembled document.
 if p.parent!=ROOT:
  content=re.sub(r'(?<=\]\()\.\./\.\./evidence/', '../evidence/',content)
  content=re.sub(r'(?<=\]\()\.\./figures/', 'figures/',content)
  content=re.sub(r'(?<=\]\()\.\./RESEARCH_QUESTION_TRACEABILITY\.md', 'RESEARCH_QUESTION_TRACEABILITY.md',content)
 text+=content+'\n\n---\n\n'
(ROOT/'DISSERTATION_DRAFT.md').write_text(text)
broken=[]
for p in ROOT.rglob('*.md'):
 for target in re.findall(r'!?\[[^\]]*\]\(([^)]+)\)',p.read_text()):
  if target.startswith(('http:','https:','mailto:','#')):continue
  local=target.split('#')[0]
  if local and not (p.parent/local).exists():broken.append({'file':str(p.relative_to(ROOT)),'target':target})
report={'source_files':[str(p.relative_to(ROOT)) for p in parts],'approximate_chapter_words':sum(len(re.findall(r"\b[\w’-]+\b",p.read_text())) for p in parts if p.parent.name=='chapters'),'broken_local_markdown_links':broken,'source_sha256':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in parts},'note':'Mechanical structure/link check, not academic approval or reference correctness verification.'}
(ROOT/'PACK_CHECKS.json').write_text(json.dumps(report,indent=2)+'\n')
assert not broken,broken
print(json.dumps({k:v for k,v in report.items() if k!='source_sha256'},indent=2))
